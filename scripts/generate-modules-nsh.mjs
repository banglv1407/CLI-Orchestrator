import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, '..');
const packsRoot = resolve(repositoryRoot, 'dist-packs');
const outputPath = resolve(repositoryRoot, 'src-tauri', 'windows', 'modules.nsh');

if (!existsSync(packsRoot)) {
  throw new Error('dist-packs is missing; stage signed modules before generating NSIS sections');
}

const modules = [];
for (const moduleId of readdirSync(packsRoot).sort()) {
  const moduleRoot = resolve(packsRoot, moduleId);
  if (!statSync(moduleRoot).isDirectory()) continue;
  const versions = readdirSync(moduleRoot)
    .filter((name) => existsSync(resolve(moduleRoot, name, 'manifest.json')))
    .sort(compareVersions)
    .reverse();
  if (versions.length === 0) continue;
  const version = versions[0];
  const packRoot = resolve(moduleRoot, version);
  const manifest = JSON.parse(readFileSync(resolve(packRoot, 'manifest.json'), 'utf8'));
  if (manifest.moduleId !== moduleId || manifest.version !== version) {
    throw new Error(`Pack path and signed manifest disagree: ${moduleId}/${version}`);
  }
  const sidecar = manifest.sidecar?.path?.split('/').at(-1);
  modules.push({
    moduleId,
    version,
    displayName: displayName(moduleId),
    symbol: moduleId.replace(/[^A-Za-z0-9]/g, '_').toUpperCase(),
    packRoot,
    sidecar,
  });
}

if (modules.length === 0) {
  throw new Error('No staged module packs were found');
}

const lines = [
  '; Generated by scripts/generate-modules-nsh.mjs. Do not edit by hand.',
  '; Fresh installs default to Core only. Rerunning Setup preselects installed modules.',
  '',
  '!macro NSIS_HOOK_PREINSTALL',
];
for (const module of modules.filter(({ sidecar }) => sidecar)) {
  lines.push(`  !insertmacro CheckIfAppIsRunning "${nsis(module.sidecar)}" "${nsis(module.displayName)}"`);
}
lines.push('!macroend', '', '!macro NSIS_HOOK_PREUNINSTALL');
for (const module of modules.filter(({ sidecar }) => sidecar)) {
  lines.push(`  !insertmacro CheckIfAppIsRunning "${nsis(module.sidecar)}" "${nsis(module.displayName)}"`);
}
lines.push(
  '!macroend',
  '',
  '!macro CLX_MODULE_INIT',
  '  Call ClxInitializeModuleSelections',
  '!macroend',
  '',
  '!macro CLX_MODULE_SECTIONS',
);
for (const module of modules) {
  lines.push(
    `  Section /o "${nsis(module.displayName)}" SEC_${module.symbol}`,
    `    SetOutPath "$INSTDIR\\modules\\${nsis(module.moduleId)}\\${nsis(module.version)}"`,
    `    File /a /r "${nsis(module.packRoot.replaceAll(sep, '\\'))}\\*.*"`,
    '  SectionEnd',
    '',
  );
}
lines.push('  Section "-Apply module selection" SEC_CLX_MODULE_SELECTION');
for (const module of modules) {
  lines.push(
    `    SectionGetFlags \${SEC_${module.symbol}} $R8`,
    '    IntOp $R8 $R8 & ${SF_SELECTED}',
    `    \${If} $R8 != \${SF_SELECTED}`,
    `      RMDir /r "$INSTDIR\\modules\\${nsis(module.moduleId)}"`,
    '    ${EndIf}',
  );
}
lines.push(
  '  SectionEnd',
  '',
  '  Function ClxInitializeModuleSelections',
);
for (const module of modules) {
  lines.push(
    `    \${If} \${FileExists} "$INSTDIR\\modules\\${nsis(module.moduleId)}\\*.*"`,
    `      SectionGetFlags \${SEC_${module.symbol}} $R8`,
    '      IntOp $R8 $R8 | ${SF_SELECTED}',
    `      SectionSetFlags \${SEC_${module.symbol}} $R8`,
    '    ${EndIf}',
  );
}
lines.push(
  '    ClearErrors',
  '    ${GetOptions} $CMDLINE "/CLXMODULES=" $R7',
  '    ${IfNot} ${Errors}',
  '      ${If} $R7 == "all"',
);
for (const module of modules) {
  lines.push(
    `        SectionGetFlags \${SEC_${module.symbol}} $R8`,
    '        IntOp $R8 $R8 | ${SF_SELECTED}',
    `        SectionSetFlags \${SEC_${module.symbol}} $R8`,
  );
}
lines.push('      ${ElseIf} $R7 == "none"');
for (const module of modules) {
  lines.push(
    `        SectionGetFlags \${SEC_${module.symbol}} $R8`,
    '        IntOp $R8 $R8 & 0xFFFFFFFE',
    `        SectionSetFlags \${SEC_${module.symbol}} $R8`,
  );
}
lines.push('      ${Else}', '        StrCpy $R6 ",$R7,"');
for (const module of modules) {
  lines.push(
    `        \${StrLoc} $R9 "$R6" ",${nsis(module.moduleId)}," ">"`,
    `        SectionGetFlags \${SEC_${module.symbol}} $R8`,
    '        ${If} $R9 == ""',
    '          IntOp $R8 $R8 & 0xFFFFFFFE',
    '        ${Else}',
    '          IntOp $R8 $R8 | ${SF_SELECTED}',
    '        ${EndIf}',
    `        SectionSetFlags \${SEC_${module.symbol}} $R8`,
  );
}
lines.push(
  '      ${EndIf}',
  '    ${EndIf}',
  '  FunctionEnd',
  '!macroend',
  '',
  '!macro CLX_MODULE_UNINSTALL',
);
for (const module of modules) {
  lines.push(`  RMDir /r "$INSTDIR\\modules\\${nsis(module.moduleId)}"`);
}
lines.push('  RMDir "$INSTDIR\\modules"', '!macroend', '');

writeFileSync(outputPath, lines.join('\n'));
process.stdout.write(`${relative(repositoryRoot, outputPath).split(sep).join('/')} (${modules.length} module pack(s))\n`);

function displayName(moduleId) {
  const known = {
    'clx.quickapps': 'Quick Apps',
    'clx.api-client': 'API Client',
    'clx.cli-proxy': 'CliProxyAI',
    'clx.ai-companion': 'AI Companion',
    'clx.local-llm': 'Local LLM (Candle Runtime)',
    'clx.ssh': 'Remote SSH & Monitoring',
    'clx.buzz': 'Buzz Workspace',
    'clx.nes': 'NES Emulator & Netplay',
    'clx.pet': 'Mythical Pet Overlay',
  };
  return known[moduleId] || moduleId;
}

function compareVersions(left, right) {
  return left.localeCompare(right, undefined, { numeric: true, sensitivity: 'base' });
}

function nsis(value) {
  if (value.includes('"') || value.includes('$') || /[\r\n]/.test(value)) {
    throw new Error(`Unsafe NSIS value: ${value}`);
  }
  return value;
}
