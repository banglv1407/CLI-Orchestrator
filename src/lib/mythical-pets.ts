// mythical-pets.ts
// Mythical creature ASCII art with multi-frame sprite-sheet animations.
// Each pet has 8 frames for smooth wing flap / run cycle.

export interface PetFrame {
  lines: string[];
  width: number;
  height: number;
}

export interface MythicalPet {
  id: string;
  name: string;
  nameVn: string;
  frames: PetFrame[];
  frameInterval: number;
  color: string;
  glowColor: string;
  scale: number;
}

function makeFrames(rawFrames: string[][], interval: number): PetFrame[] {
  return rawFrames.map((lines) => ({
    lines,
    width: Math.max(...lines.map((l) => l.length)),
    height: lines.length,
  }));
}

